// PostgreSQL DDL. The server has no single "get DDL" call, so it is put together from the catalog
// functions pg_dump also uses (pg_get_viewdef, pg_get_functiondef, pg_get_constraintdef, …).
const { qi, qname, lit } = require('./sqlgen');
const { relOid } = require('./metadata');

const DDL_DEFAULTS = { indexes: true, comments: true, triggers: true, schema: true };

async function tableDdl(conn, schema, name, o) {
  const target = o.schema ? qname(schema, name) : qi(name);
  const oid = await relOidOn(conn, schema, name);
  const cols = (await conn.execute(
    `SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, pg_get_expr(d.adbin, d.adrelid), a.attidentity,
            col_description(a.attrelid, a.attnum)
       FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`,
    [oid]
  )).rows;
  const lines = cols.map(([col, type, notNull, def, identity]) => {
    let line = `  ${qi(col)} ${type}`;
    if (identity === 'a') line += ' GENERATED ALWAYS AS IDENTITY';
    else if (identity === 'd') line += ' GENERATED BY DEFAULT AS IDENTITY';
    else if (def !== null) line += ` DEFAULT ${def}`;
    if (notNull) line += ' NOT NULL';
    return line;
  });
  const cons = (await conn.execute(
    `SELECT conname, pg_get_constraintdef(oid, true) FROM pg_constraint
      WHERE conrelid = $1 AND contype IN ('p', 'u', 'f', 'c', 'x')
      ORDER BY CASE contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 WHEN 'x' THEN 4 ELSE 5 END, conname`,
    [oid]
  )).rows;
  for (const [cname, def] of cons) lines.push(`  CONSTRAINT ${qi(cname)} ${def}`);
  const part = (await conn.execute(`SELECT pg_get_partkeydef($1::oid)`, [oid])).rows[0][0];
  const parts = [`CREATE TABLE ${target} (\n${lines.join(',\n')}\n)${part ? ` PARTITION BY ${part}` : ''};`];
  if (o.indexes) {
    const idx = await indexDdl(conn, oid);
    if (idx.length) parts.push('-- Indexes\n' + idx.join('\n'));
  }
  if (o.comments) {
    const c = [];
    const tc = (await conn.execute(`SELECT obj_description($1::oid, 'pg_class')`, [oid])).rows[0][0];
    if (tc) c.push(`COMMENT ON TABLE ${target} IS ${lit(tc)};`);
    for (const [col, , , , , comment] of cols) if (comment) c.push(`COMMENT ON COLUMN ${target}.${qi(col)} IS ${lit(comment)};`);
    if (c.length) parts.push('-- Comments\n' + c.join('\n'));
  }
  if (o.triggers) {
    const tr = (await conn.execute(`SELECT pg_get_triggerdef(oid, true) FROM pg_trigger WHERE tgrelid = $1 AND NOT tgisinternal ORDER BY tgname`, [oid])).rows;
    if (tr.length) parts.push('-- Triggers\n' + tr.map((x) => x[0] + ';').join('\n'));
  }
  return parts.join('\n\n');
}

/** Indexes that don't back a constraint (those come with the constraint). */
async function indexDdl(conn, oid) {
  const r = await conn.execute(
    `SELECT pg_get_indexdef(ix.indexrelid) FROM pg_index ix JOIN pg_class i ON i.oid = ix.indexrelid
      WHERE ix.indrelid = $1 AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = ix.indexrelid AND c.contype IN ('p', 'u', 'x'))
      ORDER BY i.relname`,
    [oid]
  );
  return r.rows.map((x) => x[0] + ';');
}

async function relOidOn(conn, schema, name) {
  const oid = await relOid({ conn }, schema, name);
  if (oid === null) throw new Error(`${schema}.${name} not found`);
  return oid;
}

async function viewDdl(conn, schema, name, type, o) {
  const target = o.schema ? qname(schema, name) : qi(name);
  const oid = await relOidOn(conn, schema, name);
  const def = String((await conn.execute(`SELECT pg_get_viewdef($1::oid, true)`, [oid])).rows[0][0] || '').trim().replace(/;$/, '');
  const mat = type === 'MATERIALIZED VIEW';
  const parts = [`${mat ? 'CREATE MATERIALIZED VIEW' : 'CREATE OR REPLACE VIEW'} ${target} AS\n${def};`];
  if (mat && o.indexes) {
    const idx = await indexDdl(conn, oid);
    if (idx.length) parts.push('-- Indexes\n' + idx.join('\n'));
  }
  if (o.comments) {
    const tc = (await conn.execute(`SELECT obj_description($1::oid, 'pg_class')`, [oid])).rows[0][0];
    if (tc) parts.push(`COMMENT ON ${mat ? 'MATERIALIZED VIEW' : 'VIEW'} ${target} IS ${lit(tc)};`);
  }
  return parts.join('\n\n');
}

async function sequenceDdl(conn, schema, name, o) {
  const r = await conn.execute(
    `SELECT format_type(seqtypid, NULL), seqstart, seqincrement, seqmin, seqmax, seqcache, seqcycle
       FROM pg_sequence q JOIN pg_class c ON c.oid = q.seqrelid JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = $1 AND c.relname = $2`,
    [schema, name]
  );
  if (!r.rows.length) return '';
  const [type, start, inc, min, max, cache, cycle] = r.rows[0];
  const target = o.schema ? qname(schema, name) : qi(name);
  return `CREATE SEQUENCE ${target}\n  AS ${type}\n  START WITH ${start}\n  INCREMENT BY ${inc}\n  MINVALUE ${min}\n  MAXVALUE ${max}\n  CACHE ${cache}${cycle ? '\n  CYCLE' : ''};`;
}

async function routineDdl(conn, schema, name, type) {
  const r = await conn.execute(
    `SELECT pg_get_functiondef(p.oid) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname = $1 AND p.proname = $2 AND p.prokind = $3 ORDER BY p.oid`,
    [schema, name, type === 'PROCEDURE' ? 'p' : 'f']
  );
  return r.rows.map((x) => String(x[0]).trim() + ';').join('\n\n');
}

async function triggerDdl(conn, schema, name) {
  const r = await conn.execute(
    `SELECT pg_get_triggerdef(t.oid, true) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
       JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = $1 AND t.tgname = $2 AND NOT t.tgisinternal`,
    [schema, name]
  );
  return r.rows.map((x) => x[0] + ';').join('\n\n');
}

async function typeDdl(conn, schema, name, o) {
  const target = o.schema ? qname(schema, name) : qi(name);
  const r = await conn.execute(
    `SELECT t.oid, t.typtype, format_type(t.typbasetype, t.typtypmod), t.typnotnull, t.typdefault, t.typrelid
       FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = $1 AND t.typname = $2`,
    [schema, name]
  );
  if (!r.rows.length) return '';
  const [oid, kind, base, notNull, def, relid] = r.rows[0];
  if (kind === 'e') {
    const labels = (await conn.execute(`SELECT enumlabel FROM pg_enum WHERE enumtypid = $1 ORDER BY enumsortorder`, [oid])).rows.map((x) => lit(x[0]));
    return `CREATE TYPE ${target} AS ENUM (${labels.join(', ')});`;
  }
  if (kind === 'd') {
    const checks = (await conn.execute(`SELECT conname, pg_get_constraintdef(oid, true) FROM pg_constraint WHERE contypid = $1 ORDER BY conname`, [oid])).rows;
    let sql = `CREATE DOMAIN ${target} AS ${base}`;
    if (def !== null) sql += ` DEFAULT ${def}`;
    if (notNull) sql += ' NOT NULL';
    for (const [cname, cdef] of checks) sql += `\n  CONSTRAINT ${qi(cname)} ${cdef}`;
    return sql + ';';
  }
  if (kind === 'c') {
    const attrs = (await conn.execute(
      `SELECT attname, format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = $1 AND attnum > 0 AND NOT attisdropped ORDER BY attnum`,
      [relid]
    )).rows.map(([a, t]) => `  ${qi(a)} ${t}`);
    return `CREATE TYPE ${target} AS (\n${attrs.join(',\n')}\n);`;
  }
  if (kind === 'r') {
    const sub = (await conn.execute(`SELECT format_type(rngsubtype, NULL) FROM pg_range WHERE rngtypid = $1`, [oid])).rows[0];
    return `CREATE TYPE ${target} AS RANGE (SUBTYPE = ${sub ? sub[0] : 'unknown'});`;
  }
  return `-- ${schema}.${name}: no DDL for this kind of type`;
}

/** DDL on a given connection (the session's, or an export's own connection). */
async function ddlOn(conn, schema, name, type, options = {}) {
  const o = { ...DDL_DEFAULTS, ...options };
  if (type === 'TABLE') return tableDdl(conn, schema, name, o);
  if (type === 'VIEW' || type === 'MATERIALIZED VIEW') return viewDdl(conn, schema, name, type, o);
  if (type === 'SEQUENCE') return sequenceDdl(conn, schema, name, o);
  if (type === 'FUNCTION' || type === 'PROCEDURE') return routineDdl(conn, schema, name, type);
  if (type === 'TRIGGER') return triggerDdl(conn, schema, name);
  if (type === 'TYPE') return typeDdl(conn, schema, name, o);
  return `-- No DDL for ${type}`;
}

const ddl = (s, schema, name, type, options) => ddlOn(s.conn, schema, name, type, options);

module.exports = { ddl, ddlOn };
