// Run with: npm test   (no database needed)
const assert = require('assert');
const { split, statementAt } = require('../src/shared/sqlsplit');
const { buildChanges, buildWhere } = require('../src/main/db/oracle/sqlgen');

let passed = 0;
const t = (name, fn) => { fn(); passed++; console.log('  ok  ' + name); };

t('splits simple statements and drops ;', () => {
  const r = split("select 1 from dual;\nselect 'a;b' from dual;  -- c;\nselect 3 from dual");
  assert.deepStrictEqual(r.map((x) => x.text), ['select 1 from dual', "select 'a;b' from dual", 'select 3 from dual']);
});

t('keeps PL/SQL blocks whole until /', () => {
  const sql = `create or replace procedure p as\nbegin\n  null;\n  dbms_output.put_line('x;y');\nend;\n/\nselect 1 from dual;`;
  const r = split(sql);
  assert.strictEqual(r.length, 2);
  assert.ok(r[0].text.endsWith('end;'));
  assert.ok(r[0].plsql);
  assert.strictEqual(r[1].text, 'select 1 from dual');
});

t('anonymous block at end of text without /', () => {
  const r = split('begin\n  null;\nend;');
  assert.strictEqual(r.length, 1);
  assert.strictEqual(r[0].text, 'begin\n  null;\nend;');
});

t('handles q-quotes, comments and quoted identifiers', () => {
  const r = split(`select q'[it's; fine]' from "A;B"; /* x; */ select 2 from dual;`);
  assert.strictEqual(r.length, 2);
  assert.ok(r[0].text.includes(`q'[it's; fine]'`));
});

t('statementAt finds statement under cursor', () => {
  const sql = 'select 1 from dual;\n\nselect 2 from dual;';
  assert.strictEqual(statementAt(sql, 3).text, 'select 1 from dual');
  assert.strictEqual(statementAt(sql, sql.length - 2).text, 'select 2 from dual');
  assert.strictEqual(statementAt(sql, 20).text, 'select 1 from dual');
});

const cols = [
  { name: 'ID', type: 'NUMBER' },
  { name: 'NAME', type: 'VARCHAR2' },
  { name: 'CREATED', type: 'DATE' },
  { name: 'TS', type: 'TIMESTAMP(6)' },
];

t('builds bound UPDATE/INSERT/DELETE', () => {
  const st = buildChanges('HR', 'EMP', cols, {
    updates: [{ rowid: 'AAA', values: { NAME: "O'Neil", CREATED: '2026-01-02' } }],
    inserts: [{ values: { ID: '5', NAME: null } }],
    deletes: [{ rowid: 'BBB' }],
  });
  assert.strictEqual(st.length, 3);
  assert.strictEqual(st[0].sql, 'DELETE FROM "HR"."EMP" WHERE ROWID = :rid');
  assert.strictEqual(st[1].sql, `UPDATE "HR"."EMP" SET "NAME" = :v0, "CREATED" = TO_DATE(:v1, 'YYYY-MM-DD HH24:MI:SS') WHERE ROWID = :rid`);
  assert.deepStrictEqual(st[1].binds, { rid: 'AAA', v0: "O'Neil", v1: '2026-01-02 00:00:00' });
  assert.ok(st[1].preview.includes("'O''Neil'"));
  assert.strictEqual(st[2].sql, 'INSERT INTO "HR"."EMP" ("ID", "NAME") VALUES (:v0, NULL)');
});

t('rejects unknown columns', () => {
  assert.throws(() => buildChanges('HR', 'EMP', cols, { updates: [{ rowid: 'A', values: { 'X" = 1 --': 1 } }] }));
});

t('builds WHERE with binds', () => {
  const w = buildWhere(cols, [
    { col: 'NAME', op: 'CONTAINS', value: 'li' },
    { col: 'ID', op: 'IN', value: '1, 2' },
    { col: 'CREATED', op: '>=', value: '2026-01-01' },
    { col: 'TS', op: 'IS NULL' },
    { col: 'NOPE', op: '=', value: 'x' },
  ]);
  assert.strictEqual(w.where, ` WHERE "NAME" LIKE :f0 AND "ID" IN (:f1_0, :f1_1) AND "CREATED" >= TO_DATE(:f2, 'YYYY-MM-DD HH24:MI:SS') AND "TS" IS NULL`);
  assert.deepStrictEqual(w.binds, { f0: '%li%', f1_0: '1', f1_1: '2', f2: '2026-01-01 00:00:00' });
});

const { formatScript } = require('../src/main/format');
const oracleDialect = require('../src/main/db/oracle/dialect');
t('beautify keeps comments and PL/SQL, formats SQL', () => {
  const r = formatScript("-- c\nselect a from t where x=1;\nbegin\n  null;\nend;\n/\nselect 1 from dual", oracleDialect);
  assert.ok(r.text.startsWith('-- c\nSELECT\n  a\nFROM\n  t\nWHERE\n  x = 1;'));
  assert.ok(r.text.includes('begin\n  null;\nend;\n/'));
  assert.deepStrictEqual([r.formatted, r.plsql, r.skipped], [2, 1, 0]);
});
t('beautify leaves unparseable statements alone', () => {
  const r = formatScript('select from where ((;', oracleDialect);
  assert.strictEqual(r.text, 'select from where ((;');
  assert.strictEqual(r.skipped, 1);
});

const { buildCreateTable } = require('../src/main/db/oracle/sqlgen');
t('CREATE TABLE with defaults, NOT NULL and primary key', () => {
  const r = buildCreateTable({
    owner: 'HR', name: 'untitled_table_11077',
    columns: [
      { name: 'id', type: 'NUMBER GENERATED BY DEFAULT AS IDENTITY', nullable: true },
      { name: 'name', type: 'VARCHAR2(120)', nullable: false },
      { name: 'created_at', type: 'DATE', nullable: false, default: 'SYSDATE' },
      { name: 'status', type: 'CHAR(1)', default: "'A'" },
      { name: 'size', type: 'NUMBER', default: 'NULL' },
      { name: 'Mixed Case', type: 'CLOB' },
      { name: '', type: '' },
    ],
    primaryKey: ['id'],
  });
  assert.strictEqual(r.table, 'UNTITLED_TABLE_11077');
  assert.strictEqual(r.sql, [
    'CREATE TABLE "HR".untitled_table_11077 (',
    '  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,',
    '  name VARCHAR2(120) NOT NULL,',
    '  created_at DATE DEFAULT SYSDATE NOT NULL,',
    "  status CHAR(1) DEFAULT 'A',",
    '  "SIZE" NUMBER,',
    '  "Mixed Case" CLOB',
    ')',
  ].join('\n'));
});
t('CREATE TABLE: identity + PRIMARY KEY, written either way', () => {
  const want = 'CREATE TABLE my_table (\n  id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,\n  name VARCHAR2(100)\n)';
  const cols = (type) => [{ name: 'id', type }, { name: 'name', type: 'VARCHAR2(100)' }];
  assert.strictEqual(buildCreateTable({ name: 'my_table', columns: cols('NUMBER GENERATED ALWAYS AS IDENTITY'), primaryKey: ['id'] }).sql, want);
  assert.strictEqual(buildCreateTable({ name: 'my_table', columns: cols('NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY') }).sql, want);
  assert.strictEqual(buildCreateTable({ name: 'my_table', columns: cols('NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY'), primaryKey: ['id'] }).sql, want);
});
t('CREATE TABLE: composite key becomes a constraint', () => {
  const r = buildCreateTable({ name: 'order_lines', columns: [{ name: 'order_id', type: 'NUMBER' }, { name: 'line_no', type: 'NUMBER' }], primaryKey: ['order_id', 'line_no'] });
  assert.ok(r.sql.endsWith('  CONSTRAINT "ORDER_LINES_PK" PRIMARY KEY (order_id, line_no)\n)'));
});
t('CREATE TABLE validation', () => {
  assert.throws(() => buildCreateTable({ name: '', columns: [] }), /name[\s\S]*at least one column/);
  assert.throws(() => buildCreateTable({ name: 't', columns: [{ name: 'a', type: 'NUMBER' }, { name: 'A', type: 'DATE' }] }), /listed twice/);
  assert.throws(() => buildCreateTable({ name: 't', columns: [{ name: 'a', type: '' }] }), /needs a data type/);
  assert.throws(() => buildCreateTable({ name: 't', columns: [{ name: 'a', type: 'NUMBER' }], primaryKey: ['b'] }), /not in the column list/);
});

const { buildTruncate, buildDropTable } = require('../src/main/db/oracle/sqlgen');
t('TRUNCATE / DROP TABLE statements', () => {
  assert.strictEqual(buildTruncate('SYSTEM', 'UNTITLED_TABLE_96906'), 'TRUNCATE TABLE "SYSTEM"."UNTITLED_TABLE_96906"');
  assert.strictEqual(buildDropTable('HR', 'Mixed Name'), 'DROP TABLE "HR"."Mixed Name"');
  assert.strictEqual(buildDropTable('HR', 'T', { cascade: true, purge: true }), 'DROP TABLE "HR"."T" CASCADE CONSTRAINTS PURGE');
});

const { trackConnection, newLog } = require('../src/main/db');
(async () => {
  const log = newLog();
  const fake = {
    execute: async (sql) => { if (/boom/.test(sql)) throw new Error('ORA-00942: table or view does not exist\nmore'); return { rows: [[1], [2]] }; },
    commit: async () => {}, rollback: async () => {},
  };
  trackConnection(fake, log);
  await fake.execute('SELECT 1 FROM dual WHERE x = :x', { x: 5, out: { dir: 3003 } });
  await fake.execute('SELECT boom FROM t').catch(() => {});
  await fake.rawExecute('SELECT user_query FROM t');
  await fake.commit();
  t('SQL log records app queries, errors and commits but not raw (user) queries', () => {
    assert.deepStrictEqual(log.entries.map((e) => e.sql), ['SELECT 1 FROM dual WHERE x = :x', 'SELECT boom FROM t', 'COMMIT']);
    assert.deepStrictEqual(log.entries[0].binds, { x: 5, out: '<out>' });
    assert.strictEqual(log.entries[0].rows, 2);
    assert.strictEqual(log.entries[1].error, 'ORA-00942: table or view does not exist');
  });

  // Query-tab statements go through raw driver calls; the shared runner logs them (marked `user`), stopping at an error.
  const sessions = require('../src/main/db/common/sessions');
  const runLog = newLog();
  const runConn = trackConnection({ execute: async () => ({ rows: [[1]] }), commit: async () => {}, rollback: async () => {} }, runLog);
  sessions.sessions.set('log-test', { conn: runConn, log: runLog, autoCommit: true, busy: false, engine: {
    isLostError: () => false,
    async runStatement(s, sql) {
      await s.conn.execute('SELECT internal FROM dual');
      if (/fail/.test(sql)) throw new Error('ORA-00942: table or view does not exist\nmore');
      return /^select/i.test(sql) ? { kind: 'rows', rows: [[1], [2]] } : { kind: 'exec', rowsAffected: 3 };
    },
  } });
  await require('../src/main/db/common/query').run('log-test', ['select 1 from dual', 'update t set a = 1', 'select * from fail', 'select never']);
  sessions.sessions.delete('log-test');
  t('SQL log records the user queries from query tabs, in run order', () => {
    const mine = runLog.entries.filter((e) => e.user);
    assert.deepStrictEqual(mine.map((e) => e.sql), ['select 1 from dual', 'update t set a = 1', 'select * from fail']);
    assert.deepStrictEqual([mine[0].rows, mine[1].affected, mine[2].error], [2, 3, 'ORA-00942: table or view does not exist']);
    assert.deepStrictEqual(runLog.entries.map((e) => e.id), runLog.entries.map((_, i) => i + 1)); // numbered as added
  });

  t('SQL log text runs again as a script (Oracle PL/SQL blocks end with /)', () => {
    global.window = { U: { h() {}, icon() {}, toast() {} }, SqlSplit: require('../src/shared/sqlsplit') };
    require('../src/renderer/js/sqllog.js');
    const scripts = {
      oracle: "select * from dual;\ninsert into t values (1, 'a;b');\nBEGIN\n  dbms_output.put_line('hi');\nEND;\n/\nDECLARE x number; BEGIN x := 1; END;\n/\ncreate or replace procedure p as\nbegin\n  null;\nend;\n/\nselect 2 from dual",
      postgres: "BEGIN;\ncreate function f() returns int as $$ begin return 1; end; $$ language plpgsql;\nselect 'x;y';\nCOMMIT",
      mysql: "select 1;\ninsert into t values ('a;b');\nselect 3",
    };
    for (const [d, script] of Object.entries(scripts)) {
      const stmts = window.SqlSplit.split(script, d).map((s) => s.text.trim());
      const text = stmts.map((sql, i) => window.SqlLog.entryText({ id: i + 1, at: 0, ms: 1, sql, user: true }, d)).join('\n');
      const again = window.SqlSplit.split(text, d).map((s) => s.text.replace(/^(--[^\n]*\n)+/, '').trim());
      assert.deepStrictEqual(again, stmts, d);
    }
    delete global.window;
  });
  t('undo / redo is per field, and a change from code is undone first', () => {
    const on = {};
    const saved = { document: global.document, Event: global.Event, performance: global.performance };
    global.document = { addEventListener: (type, f) => { on[type] = f; } };
    global.Event = class { constructor(type) { this.type = type; } };
    global.performance = { now: () => Date.now() };
    delete require.cache[require.resolve('../src/renderer/js/undo.js')];
    require('../src/renderer/js/undo.js');
    const field = (tag) => ({ tagName: tag, value: '', getAttribute: () => 'text', setSelectionRange() {}, dispatchEvent(e) { e.target = this; on.input(e); } });
    const typeIn = (el, s) => { on.focusin({ target: el }); for (const c of s) { on.keydown({ target: el, key: c }); el.value += c; on.input({ target: el, inputType: 'insertText', data: c }); } };
    const key = (el, k, shiftKey = false) => on.keydown({ target: el, key: k, ctrlKey: true, shiftKey, preventDefault() {} });
    const search = field('INPUT');
    const editor = field('TEXTAREA');
    typeIn(search, 'users');
    typeIn(editor, 'select 1');
    key(editor, 'z');
    assert.deepStrictEqual([editor.value, search.value], ['select ', 'users']); // the editor's undo leaves the search box alone
    key(editor, 'y');
    assert.strictEqual(editor.value, 'select 1');
    editor.value = 'set from code';
    key(editor, 'z');
    assert.strictEqual(editor.value, 'select 1');
    key(editor, 'z', true);
    assert.strictEqual(editor.value, 'set from code');
    Object.assign(global, saved);
  });
  console.log(`\n${passed} tests passed`);
})();
