  await t('table design: create, alter in one transaction (all or nothing), truncate, drop with cascade', async () => {
    // A Structure plan built from the table as it is, like the window does.
    const planOf = async (table) => {
      const st = await db.structure(W, S, table);
      return {
        owner: S, table,
        columns: st.columns.map((c) => ({ orig: { name: c.name, type: c.fullType, nullable: c.nullable, default: c.default, comment: c.comments || '', identity: c.identity }, name: c.name, type: c.fullType, nullable: c.nullable, default: c.identity ? '' : (c.default || ''), comment: c.comments || '', drop: false })),
        dropConstraints: [], addConstraints: [], dropIndexes: [], addIndexes: [], tableComment: { from: st.comment || '', to: st.comment || '' }, st,
      };
    };
    const spec = { owner: S, name: 'Design Me', columns: [{ name: 'id', type: 'integer GENERATED BY DEFAULT AS IDENTITY' }, { name: 'Code', type: 'varchar(10)', nullable: false }, { name: 'qty', type: 'integer', default: '0' }], primaryKey: ['id'] };
    assert.strictEqual(await db.createTableSql(W, spec), 'CREATE TABLE lookup_test."Design Me" (\n  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  "Code" varchar(10) NOT NULL,\n  qty integer DEFAULT 0\n)');
    assert.deepStrictEqual((await db.createTable(W, spec)).table, 'Design Me');
    await assert.rejects(db.createTableSql(W, { owner: S, name: 'x', columns: [{ name: 'a', type: '' }, { name: 'a', type: 'int' }] }), /needs a data type[\s\S]*listed twice/);
    await admin.query(`INSERT INTO lookup_test."Design Me" ("Code", qty) VALUES ('A', 1), ('B', 2)`);
    let plan = await planOf('Design Me');
    const col = (n) => plan.columns.find((c) => c.name === n);
    Object.assign(col('qty'), { name: 'quantity', type: 'bigint', default: '5', comment: 'How many' });
    col('Code').nullable = true;
    plan.columns.push({ orig: null, name: 'customer_id', type: 'integer', nullable: true, default: '', comment: '', drop: false });
    plan.addConstraints = [{ kind: 'UNIQUE', name: '', columns: ['Code'] }, { kind: 'CHECK', name: 'qty_positive', check: 'quantity >= 0' }, { kind: 'FOREIGN KEY', name: '', columns: ['customer_id'], refTable: 'customers', refColumns: ['id'], onDelete: 'SET NULL' }];
    plan.addIndexes = [{ name: '', unique: false, columns: ['quantity'] }]; // the window offers the columns' new names
    plan.tableComment.to = 'Made by the test';
    const steps = await db.alterTableSql(W, plan);
    assert.deepStrictEqual(steps.map((x) => x.sql), [
      'ALTER TABLE lookup_test."Design Me" RENAME COLUMN qty TO quantity',
      'ALTER TABLE lookup_test."Design Me" ALTER COLUMN "Code" DROP NOT NULL',
      'ALTER TABLE lookup_test."Design Me" ALTER COLUMN quantity TYPE bigint USING quantity::bigint',
      'ALTER TABLE lookup_test."Design Me" ALTER COLUMN quantity SET DEFAULT 5',
      'ALTER TABLE lookup_test."Design Me" ADD COLUMN customer_id integer',
      'ALTER TABLE lookup_test."Design Me" ADD CONSTRAINT "Design_Me_Code_key" UNIQUE ("Code")',
      'ALTER TABLE lookup_test."Design Me" ADD CONSTRAINT qty_positive CHECK (quantity >= 0)',
      'ALTER TABLE lookup_test."Design Me" ADD CONSTRAINT "Design_Me_customer_id_fkey" FOREIGN KEY (customer_id) REFERENCES lookup_test.customers (id) ON DELETE SET NULL',
      'CREATE INDEX "Design_Me_quantity_idx" ON lookup_test."Design Me" (quantity)',
      "COMMENT ON TABLE lookup_test.\"Design Me\" IS 'Made by the test'",
      "COMMENT ON COLUMN lookup_test.\"Design Me\".quantity IS 'How many'",
    ]);
    let r = await db.alterTable(W, plan);
    assert.strictEqual(r.ok, true, r.error);
    let st = await db.structure(W, S, 'Design Me');
    assert.deepStrictEqual(st.columns.map((c) => [c.name, c.fullType, c.nullable, c.default]), [['id', 'integer', false, null], ['Code', 'character varying(10)', true, null], ['quantity', 'bigint', true, '5'], ['customer_id', 'integer', true, null]]);
    assert.deepStrictEqual(st.constraints.map((c) => c.type).sort(), ['CHECK', 'FOREIGN KEY', 'PRIMARY KEY', 'UNIQUE']);
    assert.strictEqual(st.comment, 'Made by the test');
    assert.strictEqual(st.columns[2].comments, 'How many');
    // One failing step: nothing of the change is applied (PostgreSQL DDL is transactional).
    plan = await planOf('Design Me');
    plan.columns.find((c) => c.name === 'Code').name = 'code_renamed';
    plan.addConstraints = [{ kind: 'CHECK', name: 'never', check: 'quantity < 0' }];
    r = await db.alterTable(W, plan);
    assert.strictEqual(r.ok, false);
    assert.strictEqual(r.rolledBack, true);
    assert.deepStrictEqual(r.done, []);
    assert.match(r.error, /violated by some row/);
    assert.ok((await db.structure(W, S, 'Design Me')).columns.some((c) => c.name === 'Code'));
    // Drop a constraint, an index and a column.
    plan = await planOf('Design Me');
    plan.dropConstraints = [plan.st.constraints.find((c) => c.type === 'CHECK').name];
    plan.dropIndexes = ['Design_Me_quantity_idx'];
    plan.columns.find((c) => c.name === 'customer_id').drop = true;
    r = await db.alterTable(W, plan);
    assert.strictEqual(r.ok, true, r.error);
    st = await db.structure(W, S, 'Design Me');
    assert.deepStrictEqual([st.columns.length, st.constraints.some((c) => c.type === 'CHECK'), st.indexes.some((i) => i.name === 'Design_Me_quantity_idx')], [3, false, false]);
    // Inside the user's open transaction: applied under a savepoint, then committed with it.
    r = await db.run(W, ["insert into lookup_test.\"Design Me\" (\"Code\") values ('in tx')"]);
    assert.strictEqual(r[0].txOpen, true);
    plan = await planOf('Design Me');
    plan.columns.push({ orig: null, name: 'extra', type: 'text', nullable: true, default: '', comment: '', drop: false });
    assert.strictEqual((await db.alterTable(W, plan)).ok, true);
    assert.strictEqual((await admin.query(`SELECT count(*)::int AS n FROM lookup_test."Design Me" WHERE "Code" = 'in tx'`)).rows[0].n, 1);
    assert.strictEqual((await db.run(W, ['select 1']))[0].txOpen, false);
    await db.truncateTable(W, S, 'Design Me');
    assert.strictEqual((await admin.query('SELECT count(*)::int AS n FROM lookup_test."Design Me"')).rows[0].n, 0);
    await admin.query(`CREATE VIEW lookup_test.design_view AS SELECT * FROM lookup_test."Design Me"`);
    await assert.rejects(db.dropTable(W, S, 'Design Me', {}), /depend/);
    await db.dropTable(W, S, 'Design Me', { cascade: true });
    assert.strictEqual((await admin.query(`SELECT count(*)::int AS n FROM pg_class WHERE relname IN ('Design Me', 'design_view')`)).rows[0].n, 0);
  });

