// PostgreSQL engine against a real server: connect, browse, DDL, table data, queries, transactions,
// Stop, export, databases menu and lost connections. Recreates schema lookup_test (fixtures/pg-test.sql).
// Run: node test/pg-test.js   (server from LOOKUP_PG_URL, default postgres://lookup:lookup@127.0.0.1:5432/shop)
// Skips (exit 0) when no server answers.
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const db = require('../src/main/db');

const URL_ = process.env.LOOKUP_PG_URL || 'postgres://lookup:lookup@127.0.0.1:5432/shop';
const u = new URL(URL_);
const cfg = {
  engine: 'postgres', host: u.hostname, port: Number(u.port) || 5432, database: u.pathname.slice(1) || 'postgres',
  user: decodeURIComponent(u.username), password: decodeURIComponent(u.password), ssl: 'prefer', autoCommit: false,
};
const S = 'lookup_test';
const W = 101; // workspace id

let passed = 0;
const t = async (name, fn) => { await fn(); passed++; console.log('  ok ', name); };

(async () => {
  const { Client } = require('pg');
  const admin = new Client({ connectionString: URL_ });
  try { await admin.connect(); } catch (e) { console.log(`PostgreSQL tests skipped: ${e.message}`); return; }
  await admin.query(fs.readFileSync(path.join(__dirname, 'fixtures/pg-test.sql'), 'utf8'));

  await t('Test connection reports version, schema and database', async () => {
    const r = await db.test(cfg);
    assert.match(r.version, /^\d+\.\d+/);
    assert.strictEqual(r.dbName, cfg.database);
  });

  await t('connect returns the engine profile; wrong password fails clearly', async () => {
    const info = await db.connect(W, cfg);
    assert.strictEqual(info.engine.id, 'postgres');
    assert.strictEqual(info.engine.label, 'PostgreSQL');
    assert.strictEqual(info.autoCommit, false);
    await assert.rejects(db.test({ ...cfg, password: 'nope' }), /password authentication failed/);
  });

  await t('schemas mark system ones; objects list every kind', async () => {
    const schemas = await db.schemas(W);
    assert.ok(schemas.find((x) => x.name === S && !x.system));
    assert.ok(schemas.find((x) => x.name === 'pg_catalog' && x.system));
    const objs = await db.objects(W, S);
    const by = (type) => objs.filter((o) => o.type === type).map((o) => o.name).sort();
    assert.deepStrictEqual(by('TABLE'), ['audit_log', 'customers', 'orders']);
    assert.deepStrictEqual(by('VIEW'), ['big_orders']);
    assert.deepStrictEqual(by('MATERIALIZED VIEW'), ['city_counts']);
    assert.deepStrictEqual(by('SEQUENCE'), ['customers_id_seq', 'invoice_no', 'orders_id_seq']);
    assert.deepStrictEqual(by('FUNCTION'), ['log_change', 'order_total']);
    assert.deepStrictEqual(by('PROCEDURE'), ['touch_log']);
    assert.deepStrictEqual(by('TRIGGER'), ['customers_audit']);
    assert.deepStrictEqual(by('TYPE'), ['mood', 'positive_int']);
  });

  await t('columns and structure: types, keys, identity, constraints, indexes, comments', async () => {
    const cols = await db.columns(W, S, 'orders');
    const c = Object.fromEntries(cols.map((x) => [x.name, x]));
    assert.strictEqual(c.amount.fullType, 'numeric(12,2)');
    assert.strictEqual(c.amount.kind, 'number');
    assert.strictEqual(c.placed_on.kind, 'date');
    assert.strictEqual(c.placed_at.kind, 'timestamp');
    assert.strictEqual(c.photo.kind, 'binary');
    assert.strictEqual(c.customer_id.nullable, false);
    const st = await db.structure(W, S, 'customers');
    assert.ok(st.columns.find((x) => x.name === 'id' && x.pk && x.identity === 'BY DEFAULT'));
    assert.strictEqual(st.comment, 'People who buy things');
    assert.strictEqual(st.columns.find((x) => x.name === 'email').comments, 'Login e-mail');
    assert.deepStrictEqual(st.constraints.map((k) => k.type), ['PRIMARY KEY', 'UNIQUE']);
    const so = await db.structure(W, S, 'orders');
    const fk = so.constraints.find((k) => k.type === 'FOREIGN KEY');
    assert.match(fk.detail, /^→ (lookup_test\.)?customers\(id\) ON DELETE CASCADE/);
    assert.ok(so.constraints.find((k) => k.type === 'CHECK' && /amount >= 0/.test(k.detail)));
    const idx = so.indexes.find((i) => i.name === 'orders_placed_on_idx');
    assert.strictEqual(idx.columns, 'placed_on DESC');
    assert.ok(so.indexes.find((i) => i.name === 'orders_pkey').constraint);
  });

  await t('DDL for every object kind, and it recreates the table', async () => {
    const ddl = await db.ddl(W, S, 'orders', 'TABLE');
    assert.match(ddl, /^CREATE TABLE lookup_test\.orders \(\n {2}id bigint DEFAULT nextval/);
    assert.match(ddl, /"Mixed Case" text/);
    assert.match(ddl, /CONSTRAINT orders_customer_id_fkey FOREIGN KEY/);
    assert.match(ddl, /-- Indexes\nCREATE INDEX orders_placed_on_idx/);
    const cust = await db.ddl(W, S, 'customers', 'TABLE');
    assert.match(cust, /id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
    assert.match(cust, /COMMENT ON COLUMN lookup_test\.customers\.email IS 'Login e-mail';/);
    assert.match(cust, /-- Triggers\nCREATE TRIGGER customers_audit/);
    assert.match(await db.ddl(W, S, 'big_orders', 'VIEW'), /^CREATE OR REPLACE VIEW lookup_test\.big_orders AS\n/);
    assert.match(await db.ddl(W, S, 'city_counts', 'MATERIALIZED VIEW'), /^CREATE MATERIALIZED VIEW/);
    assert.match(await db.ddl(W, S, 'invoice_no', 'SEQUENCE'), /START WITH 1000\n {2}INCREMENT BY 10/);
    assert.match(await db.ddl(W, S, 'order_total', 'FUNCTION'), /CREATE OR REPLACE FUNCTION lookup_test\.order_total\(cid integer\)/);
    assert.match(await db.ddl(W, S, 'touch_log', 'PROCEDURE'), /CREATE OR REPLACE PROCEDURE/);
    assert.match(await db.ddl(W, S, 'mood', 'TYPE'), /CREATE TYPE lookup_test\.mood AS ENUM \('sad', 'ok', 'happy'\);/);
    assert.match(await db.ddl(W, S, 'positive_int', 'TYPE'), /CREATE DOMAIN lookup_test\.positive_int AS integer\n {2}CONSTRAINT/);
    assert.match(await db.ddl(W, S, 'customers_audit', 'TRIGGER'), /^CREATE TRIGGER customers_audit AFTER UPDATE/);
    // The generated DDL really works: rebuild the table in another schema.
    await admin.query('DROP SCHEMA IF EXISTS lookup_copy CASCADE; CREATE SCHEMA lookup_copy');
    const noSchema = await db.ddl(W, S, 'audit_log', 'TABLE', { schema: false });
    await admin.query(`SET search_path = lookup_copy; ${noSchema}; SET search_path = public`);
    assert.strictEqual((await admin.query(`SELECT count(*)::int n FROM information_schema.columns WHERE table_schema = 'lookup_copy'`)).rows[0].n, 2);
    await admin.query('DROP SCHEMA lookup_copy CASCADE');
  });

  await t('table data: pages in key order, count, filters, sort, values as text', async () => {
    const d = await db.tableData(W, { owner: S, name: 'orders', type: 'TABLE', offset: 0, limit: 50 });
    assert.strictEqual(d.total, 1000);
    assert.strictEqual(d.rows.length, 50);
    assert.strictEqual(d.editable, false);
    const col = (n) => d.columns.findIndex((c) => c.name === n);
    assert.strictEqual(d.rows[0][col('id')], '1');
    assert.strictEqual(d.columns[col('amount')].fullType, 'numeric(12,2)');
    assert.strictEqual(d.rows[0][col('amount')], '1.37');
    assert.strictEqual(d.rows[0][col('placed_on')], '2026-01-02');
    assert.strictEqual(d.rows[0][col('placed_at')], '2026-01-01 08:31:00.123');
    assert.strictEqual(d.rows[0][col('details')], '{"n": 1, "gift": false}');
    assert.strictEqual(d.rows[0][col('tags')], '{t1,x}');
    assert.deepStrictEqual(d.rows[0][col('photo')], { $bin: 'DEADBEEF', len: 4 });
    assert.strictEqual(d.rows[0][col('feeling')], 'ok');
    const p2 = await db.tableData(W, { owner: S, name: 'orders', type: 'TABLE', offset: 50, limit: 50, withCount: false });
    assert.strictEqual(p2.rows[0][col('id')], '51');
    assert.strictEqual(p2.total, null);
    const f = await db.tableData(W, { owner: S, name: 'customers', type: 'TABLE', limit: 500,
      filters: [{ col: 'city', op: '=', value: 'Giza' }, { col: 'name', op: 'CONTAINS', value: 'customer 1' }, { col: 'id', op: '>=', value: '100' }],
      sort: { col: 'id', dir: 'desc' } });
    assert.ok(f.total > 0 && f.rows.every((r) => r[3] === 'Giza' && Number(r[0]) >= 100));
    assert.ok(Number(f.rows[0][0]) > Number(f.rows[1][0]));
    const inn = await db.tableData(W, { owner: S, name: 'customers', type: 'TABLE', filters: [{ col: 'id', op: 'IN', value: '3, 5,7' }] });
    assert.deepStrictEqual(inn.rows.map((r) => r[0]), ['3', '5', '7']);
    const raw = await db.tableData(W, { owner: S, name: 'orders', type: 'TABLE', filters: [{ op: 'RAW', value: "details->>'gift' = 'true'" }] });
    assert.strictEqual(raw.total, 142);
    const nul = await db.tableData(W, { owner: S, name: 'audit_log', type: 'TABLE', filters: [{ col: 'message', op: 'IS NOT NULL' }] });
    assert.strictEqual(nul.total, 2);
    const v = await db.tableData(W, { owner: S, name: 'city_counts', type: 'MATERIALIZED VIEW', sort: { col: 'city', dir: 'asc' } });
    assert.deepStrictEqual(v.rows.map((r) => r[0]), ['Alexandria', 'Cairo', 'Giza']);
  });

  await t('queries: row limit, no limit, errors with position, notices, explain', async () => {
    let r = await db.run(W, ['select * from lookup_test.orders order by id'], { maxRows: 100 });
    assert.strictEqual(r[0].kind, 'rows');
    assert.strictEqual(r[0].rows.length, 100);
    assert.strictEqual(r[0].truncated, true);
    assert.strictEqual(r[0].columns.find((c) => c.name === 'amount').type, 'numeric');
    assert.strictEqual(r[0].columns.find((c) => c.name === 'feeling').type, 'lookup_test.mood');
    r = await db.run(W, ['select * from lookup_test.orders'], { maxRows: 0 });
    assert.strictEqual(r[0].rows.length, 1000);
    assert.strictEqual(r[0].truncated, false);
    r = await db.run(W, ['select 1', 'select nosuchcol from lookup_test.orders', 'select 2']);
    assert.strictEqual(r.length, 2);
    assert.strictEqual(r[1].kind, 'error');
    assert.match(r[1].message, /column "nosuchcol" does not exist/);
    assert.strictEqual(r[1].offset, 7);
    r = await db.run(W, ['call lookup_test.touch_log(\'hello\')']);
    assert.deepStrictEqual(r[0].output, ['logged hello']);
    r = await db.run(W, ['explain select * from lookup_test.orders where id = 1']);
    assert.strictEqual(r[0].kind, 'rows');
    assert.match(r[0].rows[0][0], /Index Scan using orders_pkey/);
    await db.rollback(W);
  });

  await t('manual commit: reads open no transaction; changes do; a failed statement keeps the transaction', async () => {
    let r = await db.run(W, ['select count(*) from lookup_test.customers']);
    assert.strictEqual(r[0].txOpen, false);
    r = await db.run(W, ["update lookup_test.customers set city = 'Luxor' where id = 1"]);
    assert.strictEqual(r[0].kind, 'exec');
    assert.strictEqual(r[0].rowsAffected, 1);
    assert.strictEqual(r[0].txOpen, true);
    // Not visible to another session yet.
    assert.strictEqual((await admin.query('select city from lookup_test.customers where id = 1')).rows[0].city, 'Giza');
    r = await db.run(W, ['insert into lookup_test.orders (customer_id, amount, placed_on) values (1, -5, current_date)']);
    assert.strictEqual(r[0].kind, 'error');
    assert.match(r[0].message, /orders_amount_check/);
    assert.strictEqual(r[0].txOpen, true);
    // The transaction is still usable (savepoint), and browsing still works inside it.
    r = await db.run(W, ['select city from lookup_test.customers where id = 1']);
    assert.strictEqual(r[0].rows[0][0], 'Luxor');
    await assert.rejects(db.structure(W, S, 'no_such_table'), /not found/);
    assert.ok((await db.objects(W, S)).length > 5);
    await db.commit(W);
    assert.strictEqual((await admin.query('select city from lookup_test.customers where id = 1')).rows[0].city, 'Luxor');
    r = await db.run(W, ["update lookup_test.customers set city = 'Aswan' where id = 2"]);
    await db.rollback(W);
    assert.strictEqual((await admin.query('select city from lookup_test.customers where id = 2')).rows[0].city, 'Alexandria');
    r = await db.run(W, ['select 1']);
    assert.strictEqual(r[0].txOpen, false);
    // Statements that can't run in a transaction still work.
    r = await db.run(W, ['vacuum lookup_test.audit_log']);
    assert.strictEqual(r[0].kind, 'exec');
  });

  await t('auto-commit on: every statement is committed straight away', async () => {
    await db.setAutoCommit(W, true);
    const r = await db.run(W, ["update lookup_test.customers set city = 'Siwa' where id = 3"]);
    assert.strictEqual(r[0].txOpen, false);
    assert.strictEqual((await admin.query('select city from lookup_test.customers where id = 3')).rows[0].city, 'Siwa');
    await db.setAutoCommit(W, false);
  });

  await t('Stop cancels a running statement and the session stays usable', async () => {
    const running = db.run(W, ['select pg_sleep(30)']);
    await new Promise((r) => setTimeout(r, 300));
    const t0 = Date.now();
    await db.cancel(W);
    const r = await running;
    assert.ok(Date.now() - t0 < 3000);
    assert.strictEqual(r[0].kind, 'error');
    assert.strictEqual(r[0].cancelled, true);
    assert.ok(!r[0].lost);
    assert.strictEqual((await db.run(W, ['select 42']))[0].rows[0][0], '42');
  });

  await t('export a table (filtered, CSV and SQL) and a query on a separate connection', async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lookup-pg-'));
    const csv = path.join(dir, 'o.csv');
    let res = await db.exportData(W, { jobId: 'a', format: 'csv', filePath: csv, source: 'table', owner: S, name: 'orders', type: 'TABLE',
      filters: [{ col: 'id', op: '<=', value: '3' }], sort: { col: 'id', dir: 'asc' }, columns: ['id', 'amount', 'photo'], options: {} }, () => {});
    assert.strictEqual(res.rows, 3);
    assert.strictEqual(fs.readFileSync(csv, 'utf8'), '﻿id,amount,photo\r\n1,1.37,DEADBEEF\r\n2,2.74,DEADBEEF\r\n3,4.11,DEADBEEF\r\n');
    const sql = path.join(dir, 'c.sql');
    res = await db.exportData(W, { jobId: 'b', format: 'sql', filePath: sql, source: 'table', owner: S, name: 'audit_log', type: 'TABLE',
      options: { target: 'lookup_test.audit_copy', includeDdl: true } }, () => {});
    const sqlRows = res.rows;
    const text = fs.readFileSync(sql, 'utf8');
    assert.match(text, /CREATE TABLE lookup_test\.audit_log/);
    assert.match(text, /INSERT INTO lookup_test\.audit_copy \(at, message\) VALUES \('20\d\d-[^']+', 'first'\);/);
    assert.ok(!/SET DEFINE OFF/.test(text));
    const json = path.join(dir, 'q.json');
    res = await db.exportData(W, { jobId: 'c', format: 'json', filePath: json, source: 'query', sql: 'select id, amount, photo, feeling from lookup_test.orders order by id limit 2', options: {} }, () => {});
    assert.deepStrictEqual(JSON.parse(fs.readFileSync(json, 'utf8')), [
      { id: 1, amount: 1.37, photo: 'DEADBEEF', feeling: 'ok' }, { id: 2, amount: 2.74, photo: 'DEADBEEF', feeling: 'happy' }]);
    // The SQL INSERT file loads back into PostgreSQL.
    await admin.query('CREATE TABLE lookup_test.audit_copy (at timestamptz, message text)');
    await admin.query(text.replace(/CREATE TABLE[\s\S]*?\);\n/, ''));
    assert.strictEqual((await admin.query('select count(*)::int n from lookup_test.audit_copy')).rows[0].n, sqlRows);
  });

  await t('cancel an export of a slow query', async () => {
    const f = path.join(os.tmpdir(), `lookup-pg-slow-${process.pid}.csv`);
    const p = db.exportData(W, { jobId: 'slow', format: 'csv', filePath: f, source: 'query', sql: 'select pg_sleep(20), 1', options: {} }, () => {});
    await new Promise((r) => setTimeout(r, 400));
    const t0 = Date.now();
    await db.cancelExport('slow');
    const res = await p;
    assert.ok(res.cancelled);
    assert.ok(Date.now() - t0 < 3000);
    assert.ok(!fs.existsSync(f));
  });

  await t('Beautify uses the PostgreSQL dialect', async () => {
    const { formatScript } = require('../src/main/format');
    const r = formatScript("select a::int, $1 from t where x = 'a;b';\ncreate function f() returns int as $$ select 1; $$ language sql;", db.dialectOf(W));
    assert.ok(r.text.startsWith('SELECT\n  a::INT,\n  $1\nFROM\n  t\nWHERE\n  x = \'a;b\';'), r.text);
    assert.ok(r.text.includes('$$ select 1; $$'));
  });

  await t('databases menu lists the server databases; switching keeps the login', async () => {
    const d = await db.databases(W);
    assert.strictEqual(d.current, cfg.database);
    assert.ok(d.list.find((x) => x.name === 'postgres' && x.open));
    const next = db.cfgForDatabase(cfg, { name: 'postgres' });
    assert.strictEqual(next.database, 'postgres');
    assert.notStrictEqual(db.targetKey(next), db.targetKey(cfg));
    const url = db.cfgForDatabase({ ...cfg, mode: 'string', connectString: 'postgres://a@h:5433/shop?sslmode=require' }, { name: 'other db' });
    assert.strictEqual(url.connectString, 'postgres://a@h:5433/other%20db?sslmode=require');
  });

  await t('a killed session is reported as lost; Reconnect opens a new one', async () => {
    const lost = [];
    db.setOnLost((id, msg) => lost.push([id, msg]));
    const pid = (await db.run(W, ['select pg_backend_pid()']))[0].rows[0][0];
    await admin.query('select pg_terminate_backend($1)', [pid]);
    const r = await db.run(W, ['select 1']);
    assert.strictEqual(r[0].kind, 'error');
    assert.strictEqual(r[0].lost, true);
    assert.strictEqual(lost.length, 1);
    await assert.rejects(db.objects(W, S), /Reconnect/);
    const info = await db.reconnect(W);
    assert.strictEqual(info.engine.id, 'postgres');
    assert.strictEqual((await db.run(W, ['select 7']))[0].rows[0][0], '7');
  });

  await t('an idle session killed on the server is noticed by the health check', async () => {
    const lost = [];
    db.setOnLost((id, msg) => lost.push(msg));
    const pid = (await db.run(W, ['select pg_backend_pid()']))[0].rows[0][0];
    db.configure({ healthCheckSec: 1 });
    await admin.query('select pg_terminate_backend($1)', [pid]);
    await new Promise((r) => setTimeout(r, 2500));
    db.configure({ healthCheckSec: 30 });
    assert.strictEqual(lost.length, 1);
    assert.match(lost[0], /^Connection lost: (terminating connection|Connection terminated)/);
    await db.reconnect(W);
  });

  await t('the SQL log records what Lookup ran (not the user queries)', async () => {
    const log = db.sqlLog(W);
    assert.ok(log.entries.some((e) => /current_setting\('server_version'\)/.test(e.sql)));
    assert.ok(!log.entries.some((e) => /select 7/.test(e.sql)));
  });

  await db.disconnect(W);
  await admin.query('DROP SCHEMA lookup_test CASCADE');
  await admin.end();
  console.log(`\n${passed} PostgreSQL tests passed`);
})().catch((e) => { console.error(e); process.exit(1); });
